def merge_category(
    client: LlmClient | None,
    *,
    category: str,
    summaries: list[dict[str, Any]],
    max_chars: int,
    max_tokens: int,
    retry_attempts: int,
    skip_llm: bool,
) -> dict[str, Any]:
    compacted = [compact_report_for_merge(item) for item in summaries]
    batches = split_batches(compacted, max_chars)

    if skip_llm or client is None:
        return local_category_merge(category, summaries)

    try:
        if len(batches) <= 1:
            return llm_category_merge(
                client,
                category=category,
                summaries=summaries,
                max_tokens=max_tokens,
                retry_attempts=retry_attempts,
            )

        sub_views: list[dict[str, Any]] = []
        by_id = {item["report_id"]: item for item in summaries}
        for batch in batches:
            batch_ids = [item.get("report_id") for item in batch]
            batch_summaries = [by_id[report_id] for report_id in batch_ids if report_id in by_id]
            sub_views.append(
                llm_category_merge(
                    client,
                    category=f"{category} 배치",
                    summaries=batch_summaries,
                    max_tokens=max_tokens,
                    retry_attempts=retry_attempts,
                )
            )
        final_view = llm_category_merge(
            client,
            category=f"{category} 통합",
            summaries=[
                {
                    "report_id": f"{category_slug(category)}_batch_{index + 1}",
                    "report_title": view.get("category", category),
                    "publisher": "stage1.4",
                    "category": category,
                    "overall_sentiment": view.get("overall_sentiment", "neutral"),
                    "core_summary": view.get("market_summary", ""),
                    "macro_view": view.get("macro_view", []),
                    "sector_view": view.get("sector_view", []),
                    "key_signals": view.get("key_signals", []),
                    "risks": view.get("risks", []),
                    "actionable_points": view.get("actionable_points", []),
                    "company_mentions": view.get("company_mentions", []),
                }
                for index, view in enumerate(sub_views)
            ],
            max_tokens=max_tokens,
            retry_attempts=retry_attempts,
        )
        final_view["sub_batch_count"] = len(sub_views)
        return final_view
    except Exception as error:  # noqa: BLE001
        fallback = local_category_merge(category, summaries)
        fallback["merge_method"] = "local_after_llm_error"
        fallback["llm_error"] = clip(str(error), 500)
        return fallback


def entity_frequency(summaries: list[dict[str, Any]]) -> Counter[str]:
    counter: Counter[str] = Counter()
    for summary in summaries:
        for company in summary.get("company_mentions") or []:
            if isinstance(company, dict) and company.get("name"):
                counter[compact(company["name"])] += 1
        for value in clean_list(summary.get("sector_view"), limit=5, char_limit=60):
            counter[value] += 1
    return counter


def build_local_atoms(summary: dict[str, Any], frequencies: Counter[str]) -> list[dict[str, Any]]:
    report_id = str(summary.get("report_id"))
    title = summary.get("report_title")
    category = summary.get("category")
    sentiment = normalize_sentiment(summary.get("overall_sentiment"))
    atoms: list[dict[str, Any]] = []

    def add_atom(atom_type: str, claim: str, *, entity: str = "", evidence: list[str] | None = None) -> None:
        claim_text = clip(claim, 360)
        if not claim_text:
            return
        entity_text = entity or clip(title, 80)
        freq = frequencies.get(entity_text, 1)
        atom_key = f"{report_id}|{atom_type}|{claim_text}"
        atoms.append(
            {
                "atom_id": f"{report_id}_{stable_hash(atom_key, 8)}",
                "report_id": report_id,
                "title": title,
                "publisher": summary.get("publisher") or summary.get("broker"),
                "category": category,
                "atom_type": atom_type,
                "entity": entity_text,
                "claim": claim_text,
                "direction": infer_direction(claim_text, sentiment),
                "horizon": summary.get("time_horizon", "mid_term"),
                "novelty_score": score_novelty(claim_text, entity_frequency=freq),
                "conviction_score": score_conviction(claim_text, len(evidence or [])),
                "evidence": evidence or [report_id],
                "portfolio_relevance": clean_list(summary.get("portfolio_relevance"), limit=3, char_limit=140),
                "source_fields": [],
            }
        )

    add_atom("thesis", summary.get("core_summary", ""), evidence=[report_id])
    for signal in clean_list(summary.get("key_signals"), limit=3, char_limit=240):
        add_atom("catalyst", signal, evidence=[report_id])
    for risk in clean_list(summary.get("risks"), limit=2, char_limit=240):
        add_atom("risk", risk, evidence=[report_id])
    for company in summary.get("company_mentions") or []:
        if not isinstance(company, dict) or not company.get("name"):
            continue
        name = compact(company["name"])
        key_points = clean_list(company.get("key_points"), limit=2, char_limit=180)
        catalysts = clean_list(company.get("catalysts"), limit=1, char_limit=180)
        risks = clean_list(company.get("risks"), limit=1, char_limit=160)
        claim = " / ".join(key_points + catalysts + risks)
        atom_type = "new_candidate" if summary.get("ticker_name") or any(k in claim for k in NOVELTY_KEYWORDS) else "company_view"
        add_atom(atom_type, claim or f"{name} 관련 리포트 관찰", entity=name, evidence=[report_id])

    deduped: list[dict[str, Any]] = []
    seen: set[str] = set()
    for atom in sorted(atoms, key=lambda item: (item["novelty_score"], item["conviction_score"]), reverse=True):
        key = f"{atom['atom_type']}|{atom['entity']}|{atom['claim'][:80]}"
        if key in seen:
            continue
        seen.add(key)
        deduped.append(atom)
        if len(deduped) >= 7:
            break
    return deduped


def llm_atoms_for_report(client: LlmClient, summary: dict[str, Any], retry_attempts: int) -> list[dict[str, Any]]:
    report_id = summary.get("report_id")
    messages = [
        {
            "role": "system",
            "content": (
                "너는 증권사 리포트 요약에서 투자 판단용 insight atom을 추출하는 분석기다. "
                "요약을 다시 쓰지 말고 claim 단위로 쪼개라. 반드시 JSON 객체만 출력하라."
            ),
        },
        {
            "role": "user",
            "content": json.dumps(
                {
                    "task": "extract_report_insight_atoms",
                    "report_id": report_id,
                    "required_schema": {
                        "atoms": [
                            {
                                "atom_type": "thesis|catalyst|risk|new_candidate|contradiction|portfolio_impact",
                                "entity": "",
                                "claim": "",
                                "direction": "positive|negative|neutral|mixed",
                                "horizon": "short_term|mid_term|long_term",
                                "novelty_score": 0.0,
                                "conviction_score": 0.0,
                                "evidence": [],
                            }
                        ]
                    },
                    "report_summary": compact_report_for_merge(summary, char_limit=700),
                },
                ensure_ascii=False,
            ),
        },
    ]
    result = client.complete_json(
        messages=messages,
        temperature=0.1,
        max_tokens=2200,
        retry_attempts=retry_attempts,
    )
    raw_atoms = result.payload.get("atoms", [])
    atoms: list[dict[str, Any]] = []
    if not isinstance(raw_atoms, list):
        return atoms
    for raw in raw_atoms[:7]:
        if not isinstance(raw, dict):
            continue
        claim = clip(raw.get("claim"), 360)
        if not claim:
            continue
        atom_key = f"{report_id}|{raw.get('atom_type')}|{claim}"
        atoms.append(
            {
                "atom_id": f"{report_id}_{stable_hash(atom_key, 8)}",
                "report_id": report_id,
                "title": summary.get("report_title"),
                "publisher": summary.get("publisher") or summary.get("broker"),
                "category": summary.get("category"),
                "atom_type": compact(raw.get("atom_type") or "thesis"),
                "entity": clip(raw.get("entity") or summary.get("report_title"), 80),
                "claim": claim,
                "direction": compact(raw.get("direction") or infer_direction(claim, summary.get("overall_sentiment"))),
                "horizon": compact(raw.get("horizon") or summary.get("time_horizon") or "mid_term"),
                "novelty_score": max(0.0, min(1.0, float(raw.get("novelty_score") or score_novelty(claim)))),
                "conviction_score": max(0.0, min(1.0, float(raw.get("conviction_score") or score_conviction(claim)))),
                "evidence": raw.get("evidence") if isinstance(raw.get("evidence"), list) else [report_id],
                "portfolio_relevance": clean_list(summary.get("portfolio_relevance"), limit=3, char_limit=140),
                "source_fields": ["llm_atoms"],
            }
        )
    return atoms


def build_insight_atoms(
    summaries: list[dict[str, Any]],
    *,
    client: LlmClient | None,
    llm_atoms: bool,
    retry_attempts: int,
) -> dict[str, Any]:
    frequencies = entity_frequency(summaries)
    atoms: list[dict[str, Any]] = []
    failures: list[dict[str, str]] = []
    for summary in summaries:
        local_atoms = build_local_atoms(summary, frequencies)
        if client and llm_atoms:
            try:
                report_atoms = llm_atoms_for_report(client, summary, retry_attempts)
                atoms.extend(report_atoms or local_atoms)
            except Exception as error:  # noqa: BLE001
                failures.append({"report_id": str(summary.get("report_id")), "error": clip(str(error), 300)})
                atoms.extend(local_atoms)
        else:
            atoms.extend(local_atoms)

    atom_by_id = {atom["atom_id"]: atom for atom in atoms}
    deduped = list(atom_by_id.values())
    by_type = Counter(atom.get("atom_type", "unknown") for atom in deduped)
    by_category = Counter(atom.get("category", "기타") for atom in deduped)
    top_atoms = sorted(
        deduped,
        key=lambda item: (item.get("novelty_score", 0) * 0.55 + item.get("conviction_score", 0) * 0.45),
        reverse=True,
    )[:40]
    new_candidates = [
        atom
        for atom in top_atoms
        if atom.get("atom_type") in {"new_candidate", "company_view"} and atom.get("direction") in {"positive", "mixed"}
    ][:20]
    risks = [atom for atom in top_atoms if atom.get("atom_type") == "risk" or atom.get("direction") == "negative"][:20]

    return {
        "schemaVersion": 1,
        "generated_at": now_iso(),
        "method": "llm_atoms" if llm_atoms and client else "local_atoms_from_report_summaries",
        "atom_count": len(deduped),
        "source_report_count": len(summaries),
        "type_counts": dict(by_type),
        "category_counts": dict(by_category),
        "top_atoms": top_atoms,
        "new_candidates": new_candidates,
        "risk_atoms": risks,
        "atoms": deduped,
        "failures": failures,
    }


def local_final_merge(date: str, category_views: dict[str, dict[str, Any]], atom_payload: dict[str, Any]) -> dict[str, Any]:
    report_count = sum(int(view.get("report_count") or 0) for view in category_views.values())
    sentiment_counter = Counter(view.get("overall_sentiment", "neutral") for view in category_views.values())
    top_atoms = atom_payload.get("top_atoms", [])[:12]
    new_candidates = atom_payload.get("new_candidates", [])[:10]
    risk_atoms = atom_payload.get("risk_atoms", [])[:10]
    return {
        "date": date,
        "report_count": report_count,
        "overall_sentiment": sentiment_counter.most_common(1)[0][0] if sentiment_counter else "neutral",
        "one_line": clip(" / ".join(view.get("market_summary", "") for view in category_views.values()), 500),
        "consensus": [
            {"category": category, "items": view.get("consensus_view", [])[:4]}
            for category, view in category_views.items()
        ],
        "minority_views": [
            {"category": category, "items": view.get("minority_view", [])[:3]}
            for category, view in category_views.items()
            if view.get("minority_view")
        ],
        "contradictions": [
            {"category": category, "items": view.get("contradictions", [])[:3]}
            for category, view in category_views.items()
            if view.get("contradictions")
        ],
        "top_insight_atoms": top_atoms,
        "new_candidates": new_candidates,
        "risk_atoms": risk_atoms,
        "category_views": category_views,
        "merge_method": "local",
    }


def llm_final_merge(
    client: LlmClient,
    *,
    date: str,
    category_views: dict[str, dict[str, Any]],
    atom_payload: dict[str, Any],
    max_tokens: int,
    retry_attempts: int,
) -> dict[str, Any]:
    compact_categories = {
        category: {
            "report_count": view.get("report_count"),
            "overall_sentiment": view.get("overall_sentiment"),
            "market_summary": clip(view.get("market_summary"), 260),
            "consensus_view": brief_items(view.get("consensus_view", []), limit=3, char_limit=120),
            "minority_view": brief_items(view.get("minority_view", []), limit=2, char_limit=110),
            "contradictions": brief_items(view.get("contradictions", []), limit=2, char_limit=110),
            "investment_hypothesis": clip(view.get("investment_hypothesis"), 220),
            "key_signals": brief_items(view.get("key_signals", []), limit=3, char_limit=100),
            "risks": brief_items(view.get("risks", []), limit=2, char_limit=100),
            "company_mentions": brief_company_mentions(view.get("company_mentions", []), limit=3),
            "actionable_points": brief_items(view.get("actionable_points", []), limit=2, char_limit=100),
        }
        for category, view in category_views.items()
    }
    messages = [
        {
            "role": "system",
            "content": (
                "너는 하루치 증권사 리포트 전체를 통합하는 CIO 보좌역이다. "
                "모든 카테고리 뷰와 insight atom을 이용해 해당일자 통합 요약 리포트를 만든다. "
                "평균적인 시장 코멘트로 뭉개지 말고 컨센서스, 소수의견, 충돌, 신규 후보, 포트폴리오 영향 슬롯을 분리하라. "
                "반드시 JSON 객체만 출력하라."
            ),
        },
        {
            "role": "user",
            "content": json.dumps(
                {
                    "task": "daily_full_integrated_report",
                    "date": date,
                    "required_schema": {
                        "date": date,
                        "report_count": 0,
                        "overall_sentiment": "bullish|bearish|neutral|mixed",
                        "one_line": "",
                        "today_consensus": [],
                        "minority_views": [],
                        "contradictions": [],
                        "new_candidates": [],
                        "portfolio_relevant_ideas": [],
                        "risk_watch": [],
                        "ignore_or_deprioritize": [],
                        "deep_research_questions": [],
                        "category_summaries": [],
                    },
                    "category_views": compact_categories,
                    "insight_atoms": {
                        "top_atoms": brief_atoms(atom_payload.get("top_atoms", []), limit=8, char_limit=120),
                        "new_candidates": brief_atoms(atom_payload.get("new_candidates", []), limit=6, char_limit=120),
                        "risk_atoms": brief_atoms(atom_payload.get("risk_atoms", []), limit=5, char_limit=120),
                    },
                },
                ensure_ascii=False,
            ),
        },
    ]
    result = client.complete_json(
        messages=messages,
        temperature=0.1,
        max_tokens=max_tokens,
        retry_attempts=retry_attempts,
    )
    payload = result.payload
    payload.setdefault("date", date)
    payload["merge_method"] = "llm"
    return payload


def render_markdown(date: str, final_report: dict[str, Any], category_views: dict[str, dict[str, Any]], atom_payload: dict[str, Any]) -> str:
    presentation = final_report.get("presentation")
    if not isinstance(presentation, dict):
        presentation = build_presentation_schema(date, final_report, category_views, atom_payload)
    sections = presentation.get("sections") if isinstance(presentation.get("sections"), dict) else {}
    insight_radar = sections.get("insight_radar") if isinstance(sections.get("insight_radar"), dict) else {}
    lines = [
        f"# {date} Full Daily Report",
        "",
        f"- 리포트 수: {final_report.get('report_count') or sum(int(v.get('report_count') or 0) for v in category_views.values())}",
        f"- 병합 방식: {final_report.get('merge_method', 'unknown')}",
        f"- 전체 분위기: {final_report.get('overall_sentiment', 'neutral')}",
        "",
        "## 한 줄 진단",
        f"- {final_report.get('one_line') or final_report.get('market_summary') or 'N/A'}",
        "",
        "## 인사이트 레이더",
        "",
        "### 새롭고 강한 신호",
    ]
    radar_atoms = insight_radar.get("signals") if isinstance(insight_radar.get("signals"), list) else []
    if radar_atoms:
        for atom in radar_atoms:
            lines.append(f"- {format_atom_line(atom)}")
    else:
        lines.append("- 포착된 고신뢰 신규 신호 없음")
    lines.extend(["", "### 평균에 묻히면 안 되는 리스크"])
    radar_risks = insight_radar.get("risks") if isinstance(insight_radar.get("risks"), list) else []
    if radar_risks:
        for atom in radar_risks:
            lines.append(f"- {format_atom_line(atom)}")
    else:
        lines.append("- 별도 리스크 atom 없음")
    lines.extend(["", "### 다음 검증 질문"])
    questions = insight_radar.get("questions") if isinstance(insight_radar.get("questions"), list) else []
    if questions:
        for question in questions:
            lines.append(f"- {question}")
    else:
        lines.append("- 신규 후보의 실적 연결성과 리스크 현실화 여부를 다음 리포트에서 확인")

    consensus_section = sections.get("consensus") if isinstance(sections.get("consensus"), dict) else {}
    append_claim_group_section(
        lines,
        consensus_section.get("title") or "오늘의 컨센서스",
        consensus_section.get("groups") if isinstance(consensus_section.get("groups"), list) else [],
    )
    minority_section = sections.get("minority") if isinstance(sections.get("minority"), dict) else {}
    append_claim_group_section(
        lines,
        minority_section.get("title") or "소수 의견 / 비컨센서스",
        minority_section.get("groups") if isinstance(minority_section.get("groups"), list) else [],
    )
    contradiction_section = sections.get("contradictions") if isinstance(sections.get("contradictions"), dict) else {}
    append_contradiction_section(
        lines,
        contradiction_section.get("title") or "충돌하는 시각",
        contradiction_section.get("groups") if isinstance(contradiction_section.get("groups"), list) else [],
    )
    candidate_section = sections.get("new_candidates") if isinstance(sections.get("new_candidates"), dict) else {}
    append_atom_list_section(
        lines,
        candidate_section.get("title") or "신규 후보 / 종목 아이디어",
        candidate_section.get("items") if isinstance(candidate_section.get("items"), list) else [],
    )
    risk_section = sections.get("risk_watch") if isinstance(sections.get("risk_watch"), dict) else {}
    append_atom_list_section(
        lines,
        risk_section.get("title") or "리스크 Watch",
        risk_section.get("items") if isinstance(risk_section.get("items"), list) else [],
    )

    lines.extend(["", "## 카테고리별 통합"])
    category_section = sections.get("category_summaries") if isinstance(sections.get("category_summaries"), dict) else {}
    category_groups = category_section.get("groups") if isinstance(category_section.get("groups"), list) else []
    if not category_groups:
        category_groups = [
            {
                "category": category,
                "report_count": view.get("report_count", 0),
                "summary": clip(view.get("market_summary"), 500),
                "key_signals": clean_list(view.get("key_signals"), limit=5, char_limit=220),
            }
            for category, view in category_views.items()
        ]
    for group in category_groups:
        category = group.get("category")
        lines.extend([
            "",
            f"### {category} ({group.get('report_count', 0)}건)",
            f"- {clip(group.get('summary'), 500)}",
        ])
        for signal in (group.get("key_signals") or [])[:5]:
            lines.append(f"- {clip(signal, 220)}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.detail:
        os.environ["REPORT_ORCHESTRATOR_DETAIL"] = args.detail
    config = load_config(args.config)
    date = args.effective_market_date or args.date or find_latest_summary_date(config.report_summaries_dir)

    summaries = load_report_summaries(config, date)
    state_dir = config.repo_root / "data" / "analysis-state" / date
    daily_dir = config.repo_root / "knowledge" / "daily"
    full_dir = state_dir / "full-report"
    ensure_dir(full_dir)

    client: LlmClient | None = None
    if not args.skip_llm:
        client = LlmClient(config)

    atoms_path = state_dir / "stage1-4-insight-atoms.json"
    if args.merge_only and atoms_path.exists() and not args.force:
        atom_payload = read_json(atoms_path, {})
    else:
        atom_payload = build_insight_atoms(
            summaries,
            client=client,
            llm_atoms=args.llm_atoms and not args.skip_llm,
            retry_attempts=config.merge_retry_attempts,
        )
        write_json(atoms_path, atom_payload)

    if args.atoms_only:
        print(str(atoms_path))
        return 0

    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for summary in summaries:
        groups[str(summary.get("category") or infer_summary_category(summary))].append(summary)

    category_views: dict[str, dict[str, Any]] = {}
    by_category_dir = full_dir / "by_category"
    ensure_dir(by_category_dir)
    for category, items in sorted(groups.items()):
        out_path = by_category_dir / f"{category_slug(category)}.json"
        if out_path.exists() and not args.force:
            cached = read_json(out_path, {})
            cached_meta = cached.get("meta") if isinstance(cached.get("meta"), dict) else {}
            if isinstance(cached.get("category_view"), dict) and cached_meta.get("skip_llm") == args.skip_llm:
                category_views[category] = cached["category_view"]
                continue
        view = merge_category(
            client,
            category=category,
            summaries=items,
            max_chars=args.max_category_chars,
            max_tokens=config.category_merge_max_tokens,
            retry_attempts=config.merge_retry_attempts,
            skip_llm=args.skip_llm,
        )
        view["report_count"] = len(items)
        category_views[category] = view
        write_json(
            out_path,
            {
                "meta": {
                    "schemaVersion": 1,
                    "generated_at": now_iso(),
                    "date": date,
                    "category": category,
                    "report_count": len(items),
                    "model": config.model if not args.skip_llm else "local",
                    "skip_llm": args.skip_llm,
                },
                "category_view": view,
            },
        )

    if args.skip_llm or client is None or not args.llm_final:
        final_report = local_final_merge(date, category_views, atom_payload)
        final_report["merge_method"] = "deterministic_from_category_views"
    else:
        try:
            final_report = llm_final_merge(
                client,
                date=date,
                category_views=category_views,
                atom_payload=atom_payload,
                max_tokens=config.final_merge_max_tokens,
                retry_attempts=config.merge_retry_attempts,
            )
        except Exception as error:  # noqa: BLE001
            final_report = local_final_merge(date, category_views, atom_payload)
            final_report["merge_method"] = "local_after_llm_error"
            final_report["llm_error"] = clip(str(error), 500)

    final_report["presentation"] = build_presentation_schema(date, final_report, category_views, atom_payload)

    full_payload = {
        "schemaVersion": 1,
        "generated_at": now_iso(),
        "date": date,
        "source": "all_report_summaries",
        "source_report_count": len(summaries),
        "category_count": len(category_views),
        "skip_llm": args.skip_llm,
        "detail_level": config.detail_level,
        "final_report": final_report,
        "category_views": category_views,
        "insight_atoms_path": str(atoms_path.relative_to(config.repo_root)),
    }
    json_path = state_dir / "stage1-4-full-daily-report.json"
    md_path = state_dir / "stage1-4-full-daily-report.md"
    knowledge_md_path = daily_dir / f"{date}-full-daily-report.md"
    markdown = render_markdown(date, final_report, category_views, atom_payload)
    write_json(json_path, full_payload)
    write_text(md_path, markdown)
    write_text(knowledge_md_path, markdown)

    print(str(json_path))
    print(str(atoms_path))
    print(str(knowledge_md_path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
