def find_latest_summary_date(report_summaries_dir: Path) -> str:
    dates = [
        entry.name
        for entry in report_summaries_dir.iterdir()
        if entry.is_dir() and re.fullmatch(r"\d{4}-\d{2}-\d{2}", entry.name)
    ]
    if not dates:
        raise RuntimeError(f"report_summaries 날짜 디렉터리가 없습니다: {report_summaries_dir}")
    return sorted(dates)[-1]


def load_index_by_id(config: Any, date: str) -> dict[str, dict[str, Any]]:
    index_path = config.input_root / date / "index.json"
    rows = read_json(index_path, [])
    if not isinstance(rows, list):
        return {}
    return {str(row.get("id") or ""): row for row in rows if row.get("id")}


def load_report_summaries(config: Any, date: str) -> list[dict[str, Any]]:
    summary_dir = config.report_summaries_dir / date
    if not summary_dir.exists():
        raise RuntimeError(f"report_summaries 디렉터리가 없습니다: {summary_dir}")

    index_by_id = load_index_by_id(config, date)
    summaries: list[dict[str, Any]] = []
    for path in sorted(summary_dir.glob("report_*.json")):
        payload = read_json(path, {})
        report = payload.get("report")
        if not isinstance(report, dict):
            continue
        meta = payload.get("meta") if isinstance(payload.get("meta"), dict) else {}
        report_id = str(meta.get("report_id") or path.stem)
        index_meta = index_by_id.get(report_id, {})
        category = compact(index_meta.get("category") or report.get("category") or "")
        if not category:
            category = infer_summary_category(report)
        enriched = dict(report)
        enriched.update(
            {
                "report_id": report_id,
                "category": category,
                "source_path": str(path),
                "broker": compact(index_meta.get("broker") or index_meta.get("publisher") or report.get("publisher")),
                "ticker": index_meta.get("ticker"),
                "ticker_name": index_meta.get("ticker_name"),
                "broker_opinion": index_meta.get("opinion"),
                "broker_target_price": index_meta.get("target_price"),
            }
        )
        if not enriched.get("report_title"):
            enriched["report_title"] = compact(meta.get("report_title") or index_meta.get("title") or report_id)
        summaries.append(enriched)

    if not summaries:
        raise RuntimeError(f"읽을 수 있는 report summary가 없습니다: {summary_dir}")
    return summaries


def compact_report_for_merge(summary: dict[str, Any], *, char_limit: int = 500) -> dict[str, Any]:
    companies = []
    for company in summary.get("company_mentions") or []:
        if not isinstance(company, dict):
            continue
        companies.append(
            {
                "name": clip(company.get("name"), 50),
                "ticker": company.get("ticker"),
                "rating": company.get("rating", "unknown"),
                "target_price": company.get("target_price"),
                "key_points": clean_list(company.get("key_points"), limit=2, char_limit=110),
                "catalysts": clean_list(company.get("catalysts"), limit=1, char_limit=100),
                "risks": clean_list(company.get("risks"), limit=1, char_limit=100),
            }
        )
        if len(companies) >= 4:
            break

    return {
        "report_id": summary.get("report_id"),
        "title": clip(summary.get("report_title"), 120),
        "publisher": clip(summary.get("publisher") or summary.get("broker"), 50),
        "category": summary.get("category"),
        "sentiment": normalize_sentiment(summary.get("overall_sentiment")),
        "horizon": summary.get("time_horizon", "mid_term"),
        "core_summary": clip(summary.get("core_summary"), char_limit),
        "macro_view": clean_list(summary.get("macro_view"), limit=3, char_limit=150),
        "sector_view": clean_list(summary.get("sector_view"), limit=3, char_limit=150),
        "key_signals": clean_list(summary.get("key_signals"), limit=3, char_limit=150),
        "risks": clean_list(summary.get("risks"), limit=2, char_limit=140),
        "actionable_points": clean_list(summary.get("actionable_points"), limit=2, char_limit=140),
        "company_mentions": companies,
    }


def split_batches(items: list[dict[str, Any]], max_chars: int) -> list[list[dict[str, Any]]]:
    batches: list[list[dict[str, Any]]] = []
    current: list[dict[str, Any]] = []
    current_chars = 0
    for item in items:
        size = len(json.dumps(item, ensure_ascii=False))
        if current and current_chars + size > max_chars:
            batches.append(current)
            current = []
            current_chars = 0
        current.append(item)
        current_chars += size
    if current:
        batches.append(current)
    return batches


def local_category_merge(category: str, summaries: list[dict[str, Any]]) -> dict[str, Any]:
    sentiment_counts = Counter(normalize_sentiment(item.get("overall_sentiment")) for item in summaries)
    overall = sentiment_counts.most_common(1)[0][0] if sentiment_counts else "neutral"
    pools: dict[str, list[str]] = defaultdict(list)
    companies: Counter[str] = Counter()
    report_refs = []
    for item in summaries:
        report_refs.append(
            {
                "report_id": item.get("report_id"),
                "title": clip(item.get("report_title"), 100),
                "sentiment": normalize_sentiment(item.get("overall_sentiment")),
            }
        )
        pools["summaries"].append(clip(item.get("core_summary"), 220))
        for field in ("macro_view", "sector_view", "key_signals", "risks", "actionable_points"):
            pools[field].extend(clean_list(item.get(field), limit=5, char_limit=160))
        for company in item.get("company_mentions") or []:
            if isinstance(company, dict) and company.get("name"):
                companies[compact(company["name"])] += 1

    def top_unique(field: str, limit: int = 7) -> list[str]:
        counter = Counter(text for text in pools[field] if text)
        return [text for text, _count in counter.most_common(limit)]

    company_mentions = [
        {"name": name, "mention_count": count}
        for name, count in companies.most_common(12)
    ]
    consensus = top_unique("key_signals", 6) or top_unique("summaries", 4)
    risks = top_unique("risks", 6)

    return {
        "category": category,
        "report_count": len(summaries),
        "overall_sentiment": overall,
        "market_summary": clip(" ".join(top_unique("summaries", 3)), 900),
        "consensus_view": consensus,
        "minority_view": top_unique("actionable_points", 4),
        "contradictions": [],
        "investment_hypothesis": clip(" / ".join(consensus[:3]), 500),
        "macro_view": top_unique("macro_view", 7),
        "sector_view": top_unique("sector_view", 7),
        "key_signals": top_unique("key_signals", 8),
        "risks": risks,
        "company_mentions": company_mentions,
        "actionable_points": top_unique("actionable_points", 7),
        "source_reports": report_refs,
        "merge_method": "local",
    }


