def render_markdown(date: str, final_report: dict[str, Any], category_views: dict[str, dict[str, Any]], atom_payload: dict[str, Any]) -> str:
    lines = [
        f"# {date} Full Daily Report",
        "",
        f"- 리포트 수: {final_report.get('report_count') or sum(int(v.get('report_count') or 0) for v in category_views.values())}",
        f"- 병합 방식: {final_report.get('merge_method', 'unknown')}",
        f"- 전체 분위기: {final_report.get('overall_sentiment', 'neutral')}",
        "",
        "## 한 줄 진단",
        f"- {final_report.get('one_line') or final_report.get('market_summary') or 'N/A'}",
        "",
        "## 오늘의 컨센서스",
    ]
    consensus = final_report.get("today_consensus") or final_report.get("consensus") or []
    if isinstance(consensus, list):
        for item in consensus[:10]:
            for row in format_grouped_claims(item, char_limit=300):
                lines.append(f"- {row}")
    lines.extend(["", "## 소수 의견 / 비컨센서스"])
    minority = final_report.get("minority_views") or []
    if isinstance(minority, list):
        for item in minority[:10]:
            for row in format_grouped_claims(item, char_limit=300):
                lines.append(f"- {row}")
    lines.extend(["", "## 충돌하는 시각"])
    contradictions = final_report.get("contradictions") or []
    if isinstance(contradictions, list):
        for item in contradictions[:10]:
            for row in format_grouped_contradictions(item):
                lines.append(f"- {row}")
    lines.extend(["", "## 신규 후보 / 종목 아이디어"])
    candidates = final_report.get("new_candidates") or atom_payload.get("new_candidates", [])
    if isinstance(candidates, list):
        for item in candidates[:12]:
            if isinstance(item, dict):
                label = item.get("entity") or item.get("name") or item.get("claim")
                claim = item.get("claim") or item.get("view") or item
                lines.append(f"- **{clip(label, 80)}**: {clip(claim, 260)}")
            else:
                lines.append(f"- {clip(item, 320)}")
    lines.extend(["", "## 리스크 Watch"])
    risks = final_report.get("risk_watch") or final_report.get("risk_atoms") or atom_payload.get("risk_atoms", [])
    if isinstance(risks, list):
        for item in risks[:12]:
            if isinstance(item, dict):
                lines.append(f"- {clip(item.get('entity'), 80)}: {clip(item.get('claim'), 260)}")
            else:
                lines.append(f"- {clip(item, 320)}")
    lines.extend(["", "## 카테고리별 통합"])
    for category, view in category_views.items():
        lines.extend([
            "",
            f"### {category} ({view.get('report_count', 0)}건)",
            f"- {clip(view.get('market_summary'), 500)}",
        ])
        for signal in (view.get("key_signals") or [])[:5]:
            lines.append(f"- {clip(signal, 220)}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.detail:
        os.environ["REPORT_ORCHESTRATOR_DETAIL"] = args.detail
    config = load_config(args.config)
    date = args.effective_market_date or args.date or find_latest_summary_date(config.report_summaries_dir)

    summaries = load_report_summaries(config, date)
    state_dir = config.repo_root / "data" / "analysis-state" / date
    daily_dir = config.repo_root / "knowledge" / "daily"
    full_dir = state_dir / "full-report"
    ensure_dir(full_dir)

    client: LlmClient | None = None
    if not args.skip_llm:
        client = LlmClient(config)

    atoms_path = state_dir / "stage1-4-insight-atoms.json"
    if args.merge_only and atoms_path.exists() and not args.force:
        atom_payload = read_json(atoms_path, {})
    else:
        atom_payload = build_insight_atoms(
            summaries,
            client=client,
            llm_atoms=args.llm_atoms and not args.skip_llm,
            retry_attempts=config.merge_retry_attempts,
        )
        write_json(atoms_path, atom_payload)

    if args.atoms_only:
        print(str(atoms_path))
        return 0

    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for summary in summaries:
        groups[str(summary.get("category") or infer_summary_category(summary))].append(summary)

    category_views: dict[str, dict[str, Any]] = {}
    by_category_dir = full_dir / "by_category"
    ensure_dir(by_category_dir)
    for category, items in sorted(groups.items()):
        out_path = by_category_dir / f"{category_slug(category)}.json"
        if out_path.exists() and not args.force:
            cached = read_json(out_path, {})
            cached_meta = cached.get("meta") if isinstance(cached.get("meta"), dict) else {}
            if isinstance(cached.get("category_view"), dict) and cached_meta.get("skip_llm") == args.skip_llm:
                category_views[category] = cached["category_view"]
                continue
        view = merge_category(
            client,
            category=category,
            summaries=items,
            max_chars=args.max_category_chars,
            max_tokens=config.category_merge_max_tokens,
            retry_attempts=config.merge_retry_attempts,
            skip_llm=args.skip_llm,
        )
        view["report_count"] = len(items)
        category_views[category] = view
        write_json(
            out_path,
            {
                "meta": {
                    "schemaVersion": 1,
                    "generated_at": now_iso(),
                    "date": date,
                    "category": category,
                    "report_count": len(items),
                    "model": config.model if not args.skip_llm else "local",
                    "skip_llm": args.skip_llm,
                },
                "category_view": view,
            },
        )

    if args.skip_llm or client is None or not args.llm_final:
        final_report = local_final_merge(date, category_views, atom_payload)
        final_report["merge_method"] = "deterministic_from_category_views"
    else:
        try:
            final_report = llm_final_merge(
                client,
                date=date,
                category_views=category_views,
                atom_payload=atom_payload,
                max_tokens=config.final_merge_max_tokens,
                retry_attempts=config.merge_retry_attempts,
            )
        except Exception as error:  # noqa: BLE001
            final_report = local_final_merge(date, category_views, atom_payload)
            final_report["merge_method"] = "local_after_llm_error"
            final_report["llm_error"] = clip(str(error), 500)

    full_payload = {
        "schemaVersion": 1,
        "generated_at": now_iso(),
        "date": date,
        "source": "all_report_summaries",
        "source_report_count": len(summaries),
        "category_count": len(category_views),
        "skip_llm": args.skip_llm,
        "detail_level": config.detail_level,
        "final_report": final_report,
        "category_views": category_views,
        "insight_atoms_path": str(atoms_path.relative_to(config.repo_root)),
    }
    json_path = state_dir / "stage1-4-full-daily-report.json"
    md_path = state_dir / "stage1-4-full-daily-report.md"
    knowledge_md_path = daily_dir / f"{date}-full-daily-report.md"
    markdown = render_markdown(date, final_report, category_views, atom_payload)
    write_json(json_path, full_payload)
    write_text(md_path, markdown)
    write_text(knowledge_md_path, markdown)

    print(str(json_path))
    print(str(atoms_path))
    print(str(knowledge_md_path))
    return 0


