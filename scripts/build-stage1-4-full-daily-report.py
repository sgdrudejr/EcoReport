"""Stage 1.4 full daily report builder.

This stage consumes every per-report summary generated by the Windows local LLM
orchestrator and creates two parallel artifacts:

1. a category-first daily integrated report using all report summaries
2. report-level insight atoms for novelty, minority views, contradictions, and
   new candidate discovery

It intentionally does not top-N filter report_summaries. Top-N selection can
still be used later for Deep Research prompts, but this file is the full daily
source of truth.
"""

