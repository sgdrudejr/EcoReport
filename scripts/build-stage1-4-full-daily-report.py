NEGATIVE_KEYWORDS = ["리스크", "우려", "하향", "둔화", "부담", "감소", "압박", "실패", "취소"]
POSITIVE_KEYWORDS = ["상향", "개선", "성장", "호조", "수혜", "증가", "강세", "반등", "매력", "수주"]


def now_iso() -> str:
    return dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat()


def compact(value: Any) -> str:
    return " ".join(str(value or "").replace("\n", " ").split()).strip()


def clip(value: Any, limit: int) -> str:
    text = compact(value)
    if len(text) <= limit:
        return text
    return text[: max(0, limit - 1)].rstrip() + "…"


def stable_hash(value: str, length: int = 10) -> str:
    return hashlib.sha1(value.encode("utf-8")).hexdigest()[:length]


def normalize_sentiment(value: Any) -> str:
    raw = compact(value).lower()
    if raw in {"bullish", "bearish", "neutral", "mixed"}:
        return raw
    if any(token in raw for token in ("긍정", "매수", "상승", "강세", "bull")):
        return "bullish"
    if any(token in raw for token in ("부정", "매도", "하락", "약세", "bear")):
        return "bearish"
    return "neutral"


def infer_direction(text: str, fallback: str = "neutral") -> str:
    normalized = compact(text)
    pos = sum(1 for keyword in POSITIVE_KEYWORDS if keyword in normalized)
    neg = sum(1 for keyword in NEGATIVE_KEYWORDS if keyword in normalized)
    if pos > neg:
        return "positive"
    if neg > pos:
        return "negative"
    sentiment = normalize_sentiment(fallback)
    if sentiment == "bullish":
        return "positive"
    if sentiment == "bearish":
        return "negative"
    return "neutral"


def score_novelty(text: str, *, entity_frequency: int = 1) -> float:
    normalized = compact(text)
    hits = sum(1 for keyword in NOVELTY_KEYWORDS if keyword in normalized)
    inverse_frequency_bonus = 0.18 if entity_frequency <= 1 else 0.08 if entity_frequency <= 3 else 0.0
    score = 0.28 + min(0.42, hits * 0.07) + inverse_frequency_bonus
    return round(max(0.05, min(0.95, score)), 3)


def score_conviction(text: str, evidence_count: int = 1) -> float:
    normalized = compact(text)
    number_bonus = min(0.2, len(re.findall(r"\d", normalized)) * 0.01)
    length_bonus = 0.12 if len(normalized) >= 80 else 0.04
    evidence_bonus = min(0.22, evidence_count * 0.055)
    return round(max(0.1, min(0.95, 0.28 + number_bonus + length_bonus + evidence_bonus)), 3)


def clean_list(values: Any, *, limit: int = 5, char_limit: int = 180) -> list[str]:
    if not isinstance(values, list):
        return []
    result: list[str] = []
    seen: set[str] = set()
    for value in values:
        text = clip(value, char_limit)
        key = text.lower()
        if not text or key in seen:
            continue
        seen.add(key)
        result.append(text)
        if len(result) >= limit:
            break
    return result


def compact_prompt_value(value: Any, *, list_limit: int = 5, string_limit: int = 180) -> Any:
    if isinstance(value, str):
        return clip(value, string_limit)
    if isinstance(value, (int, float, bool)) or value is None:
        return value
    if isinstance(value, list):
        return [
            compact_prompt_value(item, list_limit=list_limit, string_limit=string_limit)
            for item in value[:list_limit]
        ]
    if isinstance(value, dict):
        return {
            str(key): compact_prompt_value(item, list_limit=list_limit, string_limit=string_limit)
            for key, item in value.items()
            if item not in ("", None, [], {})
        }
    return clip(value, string_limit)


def brief_items(values: Any, *, limit: int = 3, char_limit: int = 120) -> list[str]:
    if not isinstance(values, list):
        return []
    result: list[str] = []
    for value in values:
        if isinstance(value, dict):
            text = (
                value.get("claim")
                or value.get("summary")
                or value.get("topic")
                or value.get("view")
                or value.get("name")
                or json.dumps(value, ensure_ascii=False)
            )
        else:
            text = value
        clipped = clip(text, char_limit)
        if clipped:
            result.append(clipped)
        if len(result) >= limit:
            break
    return result


def brief_company_mentions(values: Any, *, limit: int = 3) -> list[str]:
    if not isinstance(values, list):
        return []
    result: list[str] = []
    for value in values:
        if isinstance(value, dict):
            name = clip(value.get("name"), 40)
            view = clip(value.get("view") or value.get("rating") or "", 80)
            text = f"{name}: {view}" if view else name
        else:
            text = clip(value, 100)
        if text:
            result.append(text)
        if len(result) >= limit:
            break
    return result


def brief_atoms(values: Any, *, limit: int = 8, char_limit: int = 120) -> list[dict[str, Any]]:
    if not isinstance(values, list):
        return []
    result: list[dict[str, Any]] = []
    for atom in values:
        if not isinstance(atom, dict):
            continue
        result.append(
            {
                "type": atom.get("atom_type"),
                "entity": clip(atom.get("entity") or atom.get("title"), 40),
                "claim": clip(atom.get("claim"), char_limit),
                "report_id": atom.get("report_id"),
            }
        )
        if len(result) >= limit:
            break
    return result


def evidence_suffix(item: dict[str, Any]) -> str:
    evidence = item.get("evidence_report_ids") or item.get("evidence") or []
    if not isinstance(evidence, list) or not evidence:
        return ""
    return f" (근거: {', '.join(str(value) for value in evidence[:4])})"


def format_claim_item(item: Any, *, char_limit: int = 300) -> str:
    if not isinstance(item, dict):
        return clip(item, char_limit)
    claim = item.get("claim") or item.get("summary") or item.get("view") or item.get("name") or item.get("topic")
    if not claim:
        return clip(json.dumps(item, ensure_ascii=False), char_limit)
    text = clip(claim, char_limit)
    why = item.get("why_it_matters")
    if why:
        text += f" - 의미: {clip(why, 180)}"
    return text + evidence_suffix(item)


def format_grouped_claims(item: Any, *, char_limit: int = 300) -> list[str]:
    if not isinstance(item, dict) or not isinstance(item.get("items"), list):
        return [format_claim_item(item, char_limit=char_limit)]
    category = clip(item.get("category"), 60)
    rows: list[str] = []
    for child in item.get("items", [])[:3]:
        prefix = f"**{category}**: " if category else ""
        rows.append(prefix + format_claim_item(child, char_limit=char_limit))
    return rows


def format_contradiction_item(item: Any) -> str:
    if not isinstance(item, dict):
        return clip(item, 360)
    topic = clip(item.get("topic") or item.get("claim") or "쟁점", 80)
    side_a = clip(item.get("side_a") or item.get("bull_case") or item.get("positive_view"), 150)
    side_b = clip(item.get("side_b") or item.get("bear_case") or item.get("negative_view"), 150)
    if side_a or side_b:
        return f"**{topic}**: A) {side_a or 'N/A'} / B) {side_b or 'N/A'}{evidence_suffix(item)}"
    return format_claim_item(item, char_limit=360)


def format_grouped_contradictions(item: Any) -> list[str]:
    if not isinstance(item, dict) or not isinstance(item.get("items"), list):
        return [format_contradiction_item(item)]
    category = clip(item.get("category"), 60)
    rows: list[str] = []
    for child in item.get("items", [])[:3]:
        prefix = f"**{category}**: " if category else ""
        rows.append(prefix + format_contradiction_item(child))
    return rows


def claim_fingerprint(value: Any) -> str:
    text = compact(value).lower()
    text = re.sub(r"\([^)]*\)", " ", text)
    text = re.sub(r"\d[\d,.\-%]*", "#", text)
    tokens = re.findall(r"[0-9a-zA-Z가-힣]+", text)
    return " ".join(tokens[:24])


def structured_claim_item(item: Any, *, char_limit: int = 300) -> dict[str, Any] | None:
    if isinstance(item, dict):
        claim = item.get("claim") or item.get("summary") or item.get("view") or item.get("name") or item.get("topic")
        if not claim:
            return None
        evidence = item.get("evidence_report_ids") or item.get("evidence") or []
        return {
            "claim": clip(claim, char_limit),
            "why_it_matters": clip(item.get("why_it_matters"), 180) if item.get("why_it_matters") else None,
            "evidence_report_ids": evidence[:5] if isinstance(evidence, list) else [],
            "fingerprint": claim_fingerprint(claim),
        }
    text = clip(item, char_limit)
    if not text:
        return None
    return {
        "claim": text,
        "why_it_matters": None,
        "evidence_report_ids": [],
        "fingerprint": claim_fingerprint(text),
    }


def flatten_group_items(group: Any) -> tuple[str | None, list[Any]]:
    if isinstance(group, dict) and isinstance(group.get("items"), list):
        return clip(group.get("category"), 80), group.get("items") or []
    return None, [group]


def build_claim_groups(
    raw_groups: Any,
    category_views: dict[str, dict[str, Any]],
    *,
    item_limit: int = 2,
    group_limit: int = 12,
    char_limit: int = 300,
) -> list[dict[str, Any]]:
    if not isinstance(raw_groups, list):
        return []
    groups: list[dict[str, Any]] = []
    global_seen: set[str] = set()
    for raw_group in raw_groups:
        category, items = flatten_group_items(raw_group)
        local_seen: set[str] = set()
        claims: list[dict[str, Any]] = []
        for item in items:
            structured = structured_claim_item(item, char_limit=char_limit)
            if not structured:
                continue
            key = structured.get("fingerprint") or claim_fingerprint(structured.get("claim"))
            if not key or key in local_seen or key in global_seen:
                continue
            local_seen.add(key)
            global_seen.add(key)
            claims.append(structured)
            if len(claims) >= item_limit:
                break
        if not claims:
            continue
        view = category_views.get(category or "", {})
        groups.append(
            {
                "category": category or "통합",
                "report_count": view.get("report_count"),
                "sentiment": view.get("overall_sentiment"),
                "summary": clip(view.get("market_summary"), 220),
                "claims": claims,
                "key_signals": clean_list(view.get("key_signals"), limit=2, char_limit=160),
            }
        )
        if len(groups) >= group_limit:
            break
    return groups


def structured_contradiction_item(item: Any, *, char_limit: int = 180) -> dict[str, Any] | None:
    if not isinstance(item, dict):
        text = clip(item, char_limit)
        if not text:
            return None
        return {
            "topic": "쟁점",
            "side_a": text,
            "side_b": "",
            "evidence_report_ids": [],
            "fingerprint": claim_fingerprint(text),
        }
    topic = item.get("topic") or item.get("claim") or "쟁점"
    side_a = item.get("side_a") or item.get("bull_case") or item.get("positive_view") or ""
    side_b = item.get("side_b") or item.get("bear_case") or item.get("negative_view") or ""
    if not topic and not side_a and not side_b:
        return None
    evidence = item.get("evidence_report_ids") or item.get("evidence") or []
    return {
        "topic": clip(topic, 100),
        "side_a": clip(side_a, char_limit),
        "side_b": clip(side_b, char_limit),
        "evidence_report_ids": evidence[:5] if isinstance(evidence, list) else [],
        "fingerprint": claim_fingerprint(f"{topic} {side_a} {side_b}"),
    }


def build_contradiction_groups(
    raw_groups: Any,
    category_views: dict[str, dict[str, Any]],
    *,
    item_limit: int = 2,
    group_limit: int = 10,
) -> list[dict[str, Any]]:
    if not isinstance(raw_groups, list):
        return []
    groups: list[dict[str, Any]] = []
    global_seen: set[str] = set()
    for raw_group in raw_groups:
        category, items = flatten_group_items(raw_group)
        rows: list[dict[str, Any]] = []
        for item in items:
            structured = structured_contradiction_item(item)
            if not structured:
                continue
            key = structured.get("fingerprint") or claim_fingerprint(structured.get("topic"))
            if not key or key in global_seen:
                continue
            global_seen.add(key)
            rows.append(structured)
            if len(rows) >= item_limit:
                break
        if not rows:
            continue
        view = category_views.get(category or "", {})
        groups.append(
            {
                "category": category or "통합",
                "report_count": view.get("report_count"),
                "summary": clip(view.get("market_summary"), 180),
                "items": rows,
            }
        )
        if len(groups) >= group_limit:
            break
    return groups


def atom_score(atom: dict[str, Any]) -> float:
    novelty = atom.get("novelty_score") if isinstance(atom.get("novelty_score"), (int, float)) else 0
    conviction = atom.get("conviction_score") if isinstance(atom.get("conviction_score"), (int, float)) else 0
    return novelty * 0.55 + conviction * 0.45


def format_atom_line(atom: Any, *, char_limit: int = 260) -> str:
    if not isinstance(atom, dict):
        return clip(atom, char_limit)
    entity = clip(atom.get("entity") or atom.get("title") or atom.get("report_id") or "insight", 80)
    claim = clip(atom.get("claim") or atom.get("summary") or atom.get("view"), char_limit)
    score = atom_score(atom)
    score_text = f" / score {score:.2f}" if score > 0 else ""
    evidence = atom.get("evidence")
    evidence_text = ""
    if isinstance(evidence, list) and evidence:
        evidence_text = f" (근거: {', '.join(str(value) for value in evidence[:3])})"
    elif atom.get("report_id"):
        evidence_text = f" (근거: {atom.get('report_id')})"
    return f"**{entity}**{score_text}: {claim}{evidence_text}"


def build_research_questions(final_report: dict[str, Any], atom_payload: dict[str, Any], *, limit: int = 5) -> list[str]:
    questions: list[str] = []
    for group in final_report.get("contradictions") or []:
        if not isinstance(group, dict):
            continue
        category = clip(group.get("category"), 40)
        for item in (group.get("items") or [])[:2]:
            if not isinstance(item, dict):
                continue
            topic = clip(item.get("topic") or item.get("claim") or "충돌 시각", 90)
            questions.append(f"{category}: {topic}에서 어느 쪽이 실적/수급 데이터로 확인되는가?")
            if len(questions) >= limit:
                return questions
    for atom in atom_payload.get("new_candidates", [])[:limit]:
        if not isinstance(atom, dict):
            continue
        entity = clip(atom.get("entity") or atom.get("title"), 80)
        if entity:
            questions.append(f"{entity}: 모멘텀이 실제 주문/실적/가이던스로 이어지는 첫 확인 지표는 무엇인가?")
        if len(questions) >= limit:
            return questions
    return questions


def build_presentation_schema(
    date: str,
    final_report: dict[str, Any],
    category_views: dict[str, dict[str, Any]],
    atom_payload: dict[str, Any],
) -> dict[str, Any]:
    radar_signals = sorted(
        [
            atom
            for atom in (final_report.get("top_insight_atoms") or atom_payload.get("top_atoms") or [])
            if isinstance(atom, dict) and atom.get("direction") in {"positive", "mixed", "neutral"}
        ],
        key=atom_score,
        reverse=True,
    )[:6]
    radar_risks = sorted(
        [atom for atom in (final_report.get("risk_atoms") or atom_payload.get("risk_atoms") or []) if isinstance(atom, dict)],
        key=atom_score,
        reverse=True,
    )[:5]
    return {
        "schemaVersion": 1,
        "date": date,
        "principles": [
            "category_header_once",
            "dedupe_claims_by_fingerprint",
            "separate_consensus_minority_contradiction",
            "prefer_structured_groups_over_flat_bullets",
        ],
        "sections": {
            "insight_radar": {
                "signals": radar_signals,
                "risks": radar_risks,
                "questions": build_research_questions(final_report, atom_payload),
            },
            "consensus": {
                "title": "오늘의 컨센서스",
                "groups": build_claim_groups(
                    final_report.get("today_consensus") or final_report.get("consensus") or [],
                    category_views,
                    item_limit=2,
                    group_limit=9,
                    char_limit=280,
                ),
            },
            "minority": {
                "title": "소수 의견 / 비컨센서스",
                "groups": build_claim_groups(
                    final_report.get("minority_views") or [],
                    category_views,
                    item_limit=2,
                    group_limit=9,
                    char_limit=280,
                ),
            },
            "contradictions": {
                "title": "충돌하는 시각",
                "groups": build_contradiction_groups(
                    final_report.get("contradictions") or [],
                    category_views,
                    item_limit=2,
                    group_limit=9,
                ),
            },
            "new_candidates": {
                "title": "신규 후보 / 종목 아이디어",
                "items": (final_report.get("new_candidates") or atom_payload.get("new_candidates") or [])[:12],
            },
            "risk_watch": {
                "title": "리스크 Watch",
                "items": (final_report.get("risk_watch") or final_report.get("risk_atoms") or atom_payload.get("risk_atoms") or [])[:12],
            },
            "category_summaries": {
                "title": "카테고리별 통합",
                "groups": [
                    {
                        "category": category,
                        "report_count": view.get("report_count", 0),
                        "summary": clip(view.get("market_summary"), 500),
                        "key_signals": clean_list(view.get("key_signals"), limit=5, char_limit=220),
                    }
                    for category, view in category_views.items()
                ],
            },
        },
    }


def evidence_label(values: Any) -> str:
    if not isinstance(values, list) or not values:
        return ""
    return f" (근거: {', '.join(str(value) for value in values[:4])})"


def render_structured_claim(item: dict[str, Any], *, prefix: str = "핵심") -> str:
    text = f"{prefix}: {clip(item.get('claim'), 320)}"
    if item.get("why_it_matters"):
        text += f" - 의미: {clip(item.get('why_it_matters'), 160)}"
    return text + evidence_label(item.get("evidence_report_ids"))


def append_claim_group_section(lines: list[str], title: str, groups: list[dict[str, Any]]) -> None:
    lines.extend(["", f"## {title}"])
    if not groups:
        lines.append("- 해당 없음")
        return
    for group in groups:
        label = group.get("category") or "통합"
        count = group.get("report_count")
        suffix = f" ({count}건)" if count else ""
        lines.extend(["", f"### {label}{suffix}"])
        if group.get("summary"):
            lines.append(f"- 요약: {clip(group.get('summary'), 260)}")
        for index, claim in enumerate(group.get("claims") or [], start=1):
            lines.append(f"- {render_structured_claim(claim, prefix=f'핵심 {index}')}")
        if group.get("key_signals"):
            lines.append(f"- 보조 신호: {' / '.join(clip(signal, 90) for signal in group.get('key_signals')[:2])}")


def append_contradiction_section(lines: list[str], title: str, groups: list[dict[str, Any]]) -> None:
    lines.extend(["", f"## {title}"])
    if not groups:
        lines.append("- 해당 없음")
        return
    for group in groups:
        label = group.get("category") or "통합"
        count = group.get("report_count")
        suffix = f" ({count}건)" if count else ""
        lines.extend(["", f"### {label}{suffix}"])
        if group.get("summary"):
            lines.append(f"- 배경: {clip(group.get('summary'), 220)}")
        for item in group.get("items") or []:
            topic = clip(item.get("topic") or "쟁점", 90)
            side_a = clip(item.get("side_a") or "N/A", 150)
            side_b = clip(item.get("side_b") or "N/A", 150)
            lines.append(f"- **{topic}**: A) {side_a} / B) {side_b}{evidence_label(item.get('evidence_report_ids'))}")


def append_atom_list_section(lines: list[str], title: str, items: list[Any], *, limit: int = 12) -> None:
    lines.extend(["", f"## {title}"])
    if not items:
        lines.append("- 해당 없음")
        return
    seen: set[str] = set()
    count = 0
    for item in items:
        if isinstance(item, dict):
            label = item.get("entity") or item.get("name") or item.get("title") or item.get("claim")
            claim = item.get("claim") or item.get("view") or item.get("summary") or ""
            key = claim_fingerprint(f"{label} {claim}")
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"- **{clip(label, 80)}**: {clip(claim, 260)}")
        else:
            key = claim_fingerprint(item)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"- {clip(item, 320)}")
        count += 1
        if count >= limit:
            break


