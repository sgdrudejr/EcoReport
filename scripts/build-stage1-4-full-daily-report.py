def find_latest_summary_date(report_summaries_dir: Path) -> str:
    dates = [
        entry.name
        for entry in report_summaries_dir.iterdir()
        if entry.is_dir() and re.fullmatch(r"\d{4}-\d{2}-\d{2}", entry.name)
    ]
    if not dates:
        raise RuntimeError(f"report_summaries 날짜 디렉터리가 없습니다: {report_summaries_dir}")
    return sorted(dates)[-1]


def load_index_by_id(config: Any, date: str) -> dict[str, dict[str, Any]]:
    index_path = config.input_root / date / "index.json"
    rows = read_json(index_path, [])
    if not isinstance(rows, list):
        return {}
    return {str(row.get("id") or ""): row for row in rows if row.get("id")}


def load_report_summaries(config: Any, date: str) -> list[dict[str, Any]]:
    summary_dir = config.report_summaries_dir / date
    if not summary_dir.exists():
        raise RuntimeError(f"report_summaries 디렉터리가 없습니다: {summary_dir}")

    index_by_id = load_index_by_id(config, date)
    summaries: list[dict[str, Any]] = []
    for path in sorted(summary_dir.glob("report_*.json")):
        payload = read_json(path, {})
        report = payload.get("report")
        if not isinstance(report, dict):
            continue
        meta = payload.get("meta") if isinstance(payload.get("meta"), dict) else {}
        report_id = str(meta.get("report_id") or path.stem)
        index_meta = index_by_id.get(report_id, {})
        category = compact(index_meta.get("category") or report.get("category") or "")
        if not category:
            category = infer_summary_category(report)
        enriched = dict(report)
        enriched.update(
            {
                "report_id": report_id,
                "category": category,
                "source_path": str(path),
                "broker": compact(index_meta.get("broker") or index_meta.get("publisher") or report.get("publisher")),
                "ticker": index_meta.get("ticker"),
                "ticker_name": index_meta.get("ticker_name"),
                "broker_opinion": index_meta.get("opinion"),
                "broker_target_price": index_meta.get("target_price"),
            }
        )
        if not enriched.get("report_title"):
            enriched["report_title"] = compact(meta.get("report_title") or index_meta.get("title") or report_id)
        summaries.append(enriched)

    if not summaries:
        raise RuntimeError(f"읽을 수 있는 report summary가 없습니다: {summary_dir}")
    return summaries


def compact_report_for_merge(summary: dict[str, Any], *, char_limit: int = 500) -> dict[str, Any]:
    companies = []
    for company in summary.get("company_mentions") or []:
        if not isinstance(company, dict):
            continue
        companies.append(
            {
                "name": clip(company.get("name"), 50),
                "ticker": company.get("ticker"),
                "rating": company.get("rating", "unknown"),
                "target_price": company.get("target_price"),
                "key_points": clean_list(company.get("key_points"), limit=2, char_limit=110),
                "catalysts": clean_list(company.get("catalysts"), limit=1, char_limit=100),
                "risks": clean_list(company.get("risks"), limit=1, char_limit=100),
            }
        )
        if len(companies) >= 4:
            break

    return {
        "report_id": summary.get("report_id"),
        "title": clip(summary.get("report_title"), 120),
        "publisher": clip(summary.get("publisher") or summary.get("broker"), 50),
        "category": summary.get("category"),
        "sentiment": normalize_sentiment(summary.get("overall_sentiment")),
        "horizon": summary.get("time_horizon", "mid_term"),
        "core_summary": clip(summary.get("core_summary"), char_limit),
        "macro_view": clean_list(summary.get("macro_view"), limit=3, char_limit=150),
        "sector_view": clean_list(summary.get("sector_view"), limit=3, char_limit=150),
        "key_signals": clean_list(summary.get("key_signals"), limit=3, char_limit=150),
        "risks": clean_list(summary.get("risks"), limit=2, char_limit=140),
        "actionable_points": clean_list(summary.get("actionable_points"), limit=2, char_limit=140),
        "company_mentions": companies,
    }


def split_batches(items: list[dict[str, Any]], max_chars: int) -> list[list[dict[str, Any]]]:
    batches: list[list[dict[str, Any]]] = []
    current: list[dict[str, Any]] = []
    current_chars = 0
    for item in items:
        size = len(json.dumps(item, ensure_ascii=False))
        if current and current_chars + size > max_chars:
            batches.append(current)
            current = []
            current_chars = 0
        current.append(item)
        current_chars += size
    if current:
        batches.append(current)
    return batches


def local_category_merge(category: str, summaries: list[dict[str, Any]]) -> dict[str, Any]:
    sentiment_counts = Counter(normalize_sentiment(item.get("overall_sentiment")) for item in summaries)
    overall = sentiment_counts.most_common(1)[0][0] if sentiment_counts else "neutral"
    pools: dict[str, list[str]] = defaultdict(list)
    companies: Counter[str] = Counter()
    report_refs = []
    for item in summaries:
        report_refs.append(
            {
                "report_id": item.get("report_id"),
                "title": clip(item.get("report_title"), 100),
                "sentiment": normalize_sentiment(item.get("overall_sentiment")),
            }
        )
        pools["summaries"].append(clip(item.get("core_summary"), 220))
        for field in ("macro_view", "sector_view", "key_signals", "risks", "actionable_points"):
            pools[field].extend(clean_list(item.get(field), limit=5, char_limit=160))
        for company in item.get("company_mentions") or []:
            if isinstance(company, dict) and company.get("name"):
                companies[compact(company["name"])] += 1

    def top_unique(field: str, limit: int = 7) -> list[str]:
        counter = Counter(text for text in pools[field] if text)
        return [text for text, _count in counter.most_common(limit)]

    company_mentions = [
        {"name": name, "mention_count": count}
        for name, count in companies.most_common(12)
    ]
    consensus = top_unique("key_signals", 6) or top_unique("summaries", 4)
    risks = top_unique("risks", 6)

    return {
        "category": category,
        "report_count": len(summaries),
        "overall_sentiment": overall,
        "market_summary": clip(" ".join(top_unique("summaries", 3)), 900),
        "consensus_view": consensus,
        "minority_view": top_unique("actionable_points", 4),
        "contradictions": [],
        "investment_hypothesis": clip(" / ".join(consensus[:3]), 500),
        "macro_view": top_unique("macro_view", 7),
        "sector_view": top_unique("sector_view", 7),
        "key_signals": top_unique("key_signals", 8),
        "risks": risks,
        "company_mentions": company_mentions,
        "actionable_points": top_unique("actionable_points", 7),
        "source_reports": report_refs,
        "merge_method": "local",
    }


def llm_category_merge(
    client: LlmClient,
    *,
    category: str,
    summaries: list[dict[str, Any]],
    max_tokens: int,
    retry_attempts: int,
) -> dict[str, Any]:
    prompt_summaries = [compact_report_for_merge(item) for item in summaries]
    messages = [
        {
            "role": "system",
            "content": (
                f"너는 '{category}' 카테고리 리포트 {len(summaries)}건을 하나의 카테고리 리포트로 병합하는 금융 분석가다. "
                "입력된 모든 report_id를 고려하되 단순 평균을 내지 말고 컨센서스, 소수 의견, 충돌, 신규 후보, 실행 체크포인트를 분리하라. "
                "반드시 JSON 객체만 출력하라. 모든 주장에는 가능한 report_id evidence를 붙여라."
            ),
        },
        {
            "role": "user",
            "content": json.dumps(
                {
                    "task": "full_category_merge_all_reports",
                    "category": category,
                    "report_count": len(summaries),
                    "required_schema": {
                        "category": category,
                        "report_count": len(summaries),
                        "overall_sentiment": "bullish|bearish|neutral|mixed",
                        "market_summary": "",
                        "consensus_view": [{"claim": "", "evidence_report_ids": []}],
                        "minority_view": [{"claim": "", "why_it_matters": "", "evidence_report_ids": []}],
                        "contradictions": [{"topic": "", "side_a": "", "side_b": "", "evidence_report_ids": []}],
                        "investment_hypothesis": "",
                        "macro_view": [],
                        "sector_view": [],
                        "key_signals": [],
                        "risks": [],
                        "company_mentions": [{"name": "", "view": "", "evidence_report_ids": []}],
                        "actionable_points": [],
                    },
                    "report_summaries": prompt_summaries,
                },
                ensure_ascii=False,
            ),
        },
    ]
    result = client.complete_json(
        messages=messages,
        temperature=0.1,
        max_tokens=max_tokens,
        retry_attempts=retry_attempts,
    )
    payload = result.payload
    payload.setdefault("category", category)
    payload.setdefault("report_count", len(summaries))
    payload["merge_method"] = "llm"
    return payload


def merge_category(
    client: LlmClient | None,
    *,
    category: str,
    summaries: list[dict[str, Any]],
    max_chars: int,
    max_tokens: int,
    retry_attempts: int,
    skip_llm: bool,
) -> dict[str, Any]:
    compacted = [compact_report_for_merge(item) for item in summaries]
    batches = split_batches(compacted, max_chars)

    if skip_llm or client is None:
        return local_category_merge(category, summaries)

    try:
        if len(batches) <= 1:
            return llm_category_merge(
                client,
                category=category,
                summaries=summaries,
                max_tokens=max_tokens,
                retry_attempts=retry_attempts,
            )

        sub_views: list[dict[str, Any]] = []
        by_id = {item["report_id"]: item for item in summaries}
        for batch in batches:
            batch_ids = [item.get("report_id") for item in batch]
            batch_summaries = [by_id[report_id] for report_id in batch_ids if report_id in by_id]
            sub_views.append(
                llm_category_merge(
                    client,
                    category=f"{category} 배치",
                    summaries=batch_summaries,
                    max_tokens=max_tokens,
                    retry_attempts=retry_attempts,
                )
            )
        final_view = llm_category_merge(
            client,
            category=f"{category} 통합",
            summaries=[
                {
                    "report_id": f"{category_slug(category)}_batch_{index + 1}",
                    "report_title": view.get("category", category),
                    "publisher": "stage1.4",
                    "category": category,
                    "overall_sentiment": view.get("overall_sentiment", "neutral"),
                    "core_summary": view.get("market_summary", ""),
                    "macro_view": view.get("macro_view", []),
                    "sector_view": view.get("sector_view", []),
                    "key_signals": view.get("key_signals", []),
                    "risks": view.get("risks", []),
                    "actionable_points": view.get("actionable_points", []),
                    "company_mentions": view.get("company_mentions", []),
                }
                for index, view in enumerate(sub_views)
            ],
            max_tokens=max_tokens,
            retry_attempts=retry_attempts,
        )
        final_view["sub_batch_count"] = len(sub_views)
        return final_view
    except Exception as error:  # noqa: BLE001
        fallback = local_category_merge(category, summaries)
        fallback["merge_method"] = "local_after_llm_error"
        fallback["llm_error"] = clip(str(error), 500)
        return fallback


def entity_frequency(summaries: list[dict[str, Any]]) -> Counter[str]:
    counter: Counter[str] = Counter()
    for summary in summaries:
        for company in summary.get("company_mentions") or []:
            if isinstance(company, dict) and company.get("name"):
                counter[compact(company["name"])] += 1
        for value in clean_list(summary.get("sector_view"), limit=5, char_limit=60):
            counter[value] += 1
    return counter


def build_local_atoms(summary: dict[str, Any], frequencies: Counter[str]) -> list[dict[str, Any]]:
    report_id = str(summary.get("report_id"))
    title = summary.get("report_title")
    category = summary.get("category")
    sentiment = normalize_sentiment(summary.get("overall_sentiment"))
    atoms: list[dict[str, Any]] = []

    def add_atom(atom_type: str, claim: str, *, entity: str = "", evidence: list[str] | None = None) -> None:
        claim_text = clip(claim, 360)
        if not claim_text:
            return
        entity_text = entity or clip(title, 80)
        freq = frequencies.get(entity_text, 1)
        atom_key = f"{report_id}|{atom_type}|{claim_text}"
        atoms.append(
            {
                "atom_id": f"{report_id}_{stable_hash(atom_key, 8)}",
                "report_id": report_id,
                "title": title,
                "publisher": summary.get("publisher") or summary.get("broker"),
                "category": category,
                "atom_type": atom_type,
                "entity": entity_text,
                "claim": claim_text,
                "direction": infer_direction(claim_text, sentiment),
                "horizon": summary.get("time_horizon", "mid_term"),
                "novelty_score": score_novelty(claim_text, entity_frequency=freq),
                "conviction_score": score_conviction(claim_text, len(evidence or [])),
                "evidence": evidence or [report_id],
                "portfolio_relevance": clean_list(summary.get("portfolio_relevance"), limit=3, char_limit=140),
                "source_fields": [],
            }
        )

    add_atom("thesis", summary.get("core_summary", ""), evidence=[report_id])
    for signal in clean_list(summary.get("key_signals"), limit=3, char_limit=240):
        add_atom("catalyst", signal, evidence=[report_id])
    for risk in clean_list(summary.get("risks"), limit=2, char_limit=240):
        add_atom("risk", risk, evidence=[report_id])
    for company in summary.get("company_mentions") or []:
        if not isinstance(company, dict) or not company.get("name"):
            continue
        name = compact(company["name"])
        key_points = clean_list(company.get("key_points"), limit=2, char_limit=180)
        catalysts = clean_list(company.get("catalysts"), limit=1, char_limit=180)
        risks = clean_list(company.get("risks"), limit=1, char_limit=160)
        claim = " / ".join(key_points + catalysts + risks)
        atom_type = "new_candidate" if summary.get("ticker_name") or any(k in claim for k in NOVELTY_KEYWORDS) else "company_view"
        add_atom(atom_type, claim or f"{name} 관련 리포트 관찰", entity=name, evidence=[report_id])

    deduped: list[dict[str, Any]] = []
    seen: set[str] = set()
    for atom in sorted(atoms, key=lambda item: (item["novelty_score"], item["conviction_score"]), reverse=True):
        key = f"{atom['atom_type']}|{atom['entity']}|{atom['claim'][:80]}"
        if key in seen:
            continue
        seen.add(key)
        deduped.append(atom)
        if len(deduped) >= 7:
            break
    return deduped


def llm_atoms_for_report(client: LlmClient, summary: dict[str, Any], retry_attempts: int) -> list[dict[str, Any]]:
    report_id = summary.get("report_id")
    messages = [
        {
            "role": "system",
            "content": (
                "너는 증권사 리포트 요약에서 투자 판단용 insight atom을 추출하는 분석기다. "
                "요약을 다시 쓰지 말고 claim 단위로 쪼개라. 반드시 JSON 객체만 출력하라."
            ),
        },
        {
            "role": "user",
            "content": json.dumps(
                {
                    "task": "extract_report_insight_atoms",
                    "report_id": report_id,
                    "required_schema": {
                        "atoms": [
                            {
                                "atom_type": "thesis|catalyst|risk|new_candidate|contradiction|portfolio_impact",
                                "entity": "",
                                "claim": "",
                                "direction": "positive|negative|neutral|mixed",
                                "horizon": "short_term|mid_term|long_term",
                                "novelty_score": 0.0,
                                "conviction_score": 0.0,
                                "evidence": [],
                            }
                        ]
                    },
                    "report_summary": compact_report_for_merge(summary, char_limit=700),
                },
                ensure_ascii=False,
            ),
        },
    ]
    result = client.complete_json(
        messages=messages,
        temperature=0.1,
        max_tokens=2200,
        retry_attempts=retry_attempts,
    )
    raw_atoms = result.payload.get("atoms", [])
    atoms: list[dict[str, Any]] = []
    if not isinstance(raw_atoms, list):
        return atoms
    for raw in raw_atoms[:7]:
        if not isinstance(raw, dict):
            continue
        claim = clip(raw.get("claim"), 360)
        if not claim:
            continue
        atom_key = f"{report_id}|{raw.get('atom_type')}|{claim}"
        atoms.append(
            {
                "atom_id": f"{report_id}_{stable_hash(atom_key, 8)}",
                "report_id": report_id,
                "title": summary.get("report_title"),
                "publisher": summary.get("publisher") or summary.get("broker"),
                "category": summary.get("category"),
                "atom_type": compact(raw.get("atom_type") or "thesis"),
                "entity": clip(raw.get("entity") or summary.get("report_title"), 80),
                "claim": claim,
                "direction": compact(raw.get("direction") or infer_direction(claim, summary.get("overall_sentiment"))),
                "horizon": compact(raw.get("horizon") or summary.get("time_horizon") or "mid_term"),
                "novelty_score": max(0.0, min(1.0, float(raw.get("novelty_score") or score_novelty(claim)))),
                "conviction_score": max(0.0, min(1.0, float(raw.get("conviction_score") or score_conviction(claim)))),
                "evidence": raw.get("evidence") if isinstance(raw.get("evidence"), list) else [report_id],
                "portfolio_relevance": clean_list(summary.get("portfolio_relevance"), limit=3, char_limit=140),
                "source_fields": ["llm_atoms"],
            }
        )
    return atoms


def build_insight_atoms(
    summaries: list[dict[str, Any]],
    *,
    client: LlmClient | None,
    llm_atoms: bool,
    retry_attempts: int,
) -> dict[str, Any]:
    frequencies = entity_frequency(summaries)
    atoms: list[dict[str, Any]] = []
    failures: list[dict[str, str]] = []
    for summary in summaries:
        local_atoms = build_local_atoms(summary, frequencies)
        if client and llm_atoms:
            try:
                report_atoms = llm_atoms_for_report(client, summary, retry_attempts)
                atoms.extend(report_atoms or local_atoms)
            except Exception as error:  # noqa: BLE001
                failures.append({"report_id": str(summary.get("report_id")), "error": clip(str(error), 300)})
                atoms.extend(local_atoms)
        else:
            atoms.extend(local_atoms)

    atom_by_id = {atom["atom_id"]: atom for atom in atoms}
    deduped = list(atom_by_id.values())
    by_type = Counter(atom.get("atom_type", "unknown") for atom in deduped)
    by_category = Counter(atom.get("category", "기타") for atom in deduped)
    top_atoms = sorted(
        deduped,
        key=lambda item: (item.get("novelty_score", 0) * 0.55 + item.get("conviction_score", 0) * 0.45),
        reverse=True,
    )[:40]
    new_candidates = [
        atom
        for atom in top_atoms
        if atom.get("atom_type") in {"new_candidate", "company_view"} and atom.get("direction") in {"positive", "mixed"}
    ][:20]
    risks = [atom for atom in top_atoms if atom.get("atom_type") == "risk" or atom.get("direction") == "negative"][:20]

    return {
        "schemaVersion": 1,
        "generated_at": now_iso(),
        "method": "llm_atoms" if llm_atoms and client else "local_atoms_from_report_summaries",
        "atom_count": len(deduped),
        "source_report_count": len(summaries),
        "type_counts": dict(by_type),
        "category_counts": dict(by_category),
        "top_atoms": top_atoms,
        "new_candidates": new_candidates,
        "risk_atoms": risks,
        "atoms": deduped,
        "failures": failures,
    }


def local_final_merge(date: str, category_views: dict[str, dict[str, Any]], atom_payload: dict[str, Any]) -> dict[str, Any]:
    report_count = sum(int(view.get("report_count") or 0) for view in category_views.values())
    sentiment_counter = Counter(view.get("overall_sentiment", "neutral") for view in category_views.values())
    top_atoms = atom_payload.get("top_atoms", [])[:12]
    new_candidates = atom_payload.get("new_candidates", [])[:10]
    risk_atoms = atom_payload.get("risk_atoms", [])[:10]
    return {
        "date": date,
        "report_count": report_count,
        "overall_sentiment": sentiment_counter.most_common(1)[0][0] if sentiment_counter else "neutral",
        "one_line": clip(" / ".join(view.get("market_summary", "") for view in category_views.values()), 500),
        "consensus": [
            {"category": category, "items": view.get("consensus_view", [])[:4]}
            for category, view in category_views.items()
        ],
        "minority_views": [
            {"category": category, "items": view.get("minority_view", [])[:3]}
            for category, view in category_views.items()
            if view.get("minority_view")
        ],
        "contradictions": [
            {"category": category, "items": view.get("contradictions", [])[:3]}
            for category, view in category_views.items()
            if view.get("contradictions")
        ],
        "top_insight_atoms": top_atoms,
        "new_candidates": new_candidates,
        "risk_atoms": risk_atoms,
        "category_views": category_views,
        "merge_method": "local",
    }


